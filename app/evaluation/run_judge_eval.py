"""Judge the agent's answers: correctness vs the reference and claim faithfulness, beyond the verifier.

Re-runs the agent on every golden question (generation is cached, so this costs retrieval time
only; answers are checked against `reports/agent_v0.json`), then calls the judge (`judge.py`) on
each answered question with the sources the answer cites. Abstentions are scored by rule:
an abstained answerable question is incorrect, an abstained unanswerable one correct; an answered
unanswerable question is incorrect without a call.

Judge validation: `data/eval/judge_labels_v0.jsonl` holds correctness labels for 22 answers
(written by reading the reference and the answer; see the file's notes). The report shows the
judge's agreement with them before any judged metric is used.

Usage:
    python -m app.evaluation.run_judge_eval                       # -> reports/judge_v0.{md,json}
    python -m app.evaluation.run_judge_eval --ids T05 T06 C05     # -> reports/judge_v0_smoke.*
"""

import argparse
import json
import logging
import time
from collections import Counter
from dataclasses import asdict, dataclass, field
from pathlib import Path

from app.agent.graph import FinRAGAgent
from app.agent.xbrl import XbrlStore
from app.config import PROJECT_ROOT, get_settings
from app.evaluation.build_golden import DEFAULT_PATH as GOLDEN_PATH
from app.evaluation.golden import load_golden
from app.evaluation.judge import Judge
from app.evaluation.run_generation_eval import _mean
from app.generation.llm import LLMError

LABELS_PATH = PROJECT_ROOT / "data" / "eval" / "judge_labels_v0.jsonl"
AGENT_REPORT = PROJECT_ROOT / "reports" / "agent_v0.json"


@dataclass
class JudgedRecord:
    id: str
    category: str
    answerable: bool
    abstained: bool
    answer: str
    correctness: str  # correct / partially_correct / incorrect
    correctness_score: float
    faithfulness: float | None = None  # None for abstentions and rule-scored answers
    judged: bool = False  # False = scored by rule (abstention or answered-unanswerable)
    missing_facts: list[str] = field(default_factory=list)
    contradicted_facts: list[str] = field(default_factory=list)
    unsupported_claims: list[str] = field(default_factory=list)  # judge: unsupported or partially supported
    verifier_supported: float | None = None  # share of claims the citation verifier accepted
    reason: str = ""
    label: str | None = None
    answer_matches_agent_v0: bool | None = None
    provider: str = ""  # judge provider
    judge_model: str = ""
    answer_model: str = ""  # model that wrote the answer ("" if refused before generation)
    tokens: int = 0
    error: str = ""


def load_labels(path: Path = LABELS_PATH) -> dict[str, str]:
    if not path.exists():
        return {}
    rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return {row["id"]: row["correctness"] for row in rows}


def summarize(records: list[JudgedRecord]) -> dict:
    ans = [r for r in records if r.answerable]
    answered = [r for r in ans if not r.abstained and not r.error]
    # Labels describe the agent_v0 answers: only answers that are still identical can be compared.
    labelled = [r for r in records if r.label and r.judged and r.answer_matches_agent_v0 is not False]
    return {
        "questions": len(records),
        "judged": sum(r.judged for r in records),
        "errors": sum(bool(r.error) for r in records),
        "correctness_all_answerable": _mean(r.correctness_score for r in ans if not r.error),
        "correctness_answered": _mean(r.correctness_score for r in answered),
        "grades_answered": dict(Counter(r.correctness for r in answered)),
        "faithfulness": _mean(r.faithfulness for r in answered),
        "verifier_claim_support": _mean(r.verifier_supported for r in answered),
        "label_agreement": _mean(float(r.correctness == r.label) for r in labelled),
        "label_agreement_lenient": _mean(  # correct vs not-correct
            float((r.correctness == "correct") == (r.label == "correct")) for r in labelled),
        "labelled": len(labelled),
        "judge_tokens": sum(r.tokens for r in records),
        "providers": dict(Counter(r.provider for r in records if r.provider)),
        "judge_models": dict(Counter(r.judge_model for r in records if r.judge_model)),
        "answer_models": dict(Counter(r.answer_model for r in records if r.answer_model)),
    }


def render_report(records: list[JudgedRecord], summary: dict, title: str = "judge_v0") -> str:
    labelled = [r for r in records if r.label and r.judged and r.answer_matches_agent_v0 is not False]
    grades = ("correct", "partially_correct", "incorrect")

    def counts(key: str) -> str:
        return ", ".join(f"{k} ({v})" for k, v in summary.get(key, {}).items()) or "-"

    lines = [
        f"# Judged answers: {title}", "",
        "Generated by `python -m app.evaluation.run_judge_eval`; agent answers re-run from cache and checked "
        "against `reports/agent_v0.json`.", "",
        f"- Answers by: {counts('answer_models')}",
        f"- Judge: {counts('judge_models') if summary.get('judge_models') else counts('providers')}", "",
        "## Judge validation against hand labels", "",
        f"{summary['labelled']} labelled answers still identical to agent_v0 (`data/eval/judge_labels_v0.jsonl`). Exact agreement "
        f"**{summary['label_agreement']:.2f}**; correct vs not-correct **{summary['label_agreement_lenient']:.2f}**.", "",
        "| Label \\ Judge | " + " | ".join(grades) + " |", "|---|---|---|---|",
    ]
    for g in grades:
        row = [sum(r.label == g and r.correctness == j for r in labelled) for j in grades]
        lines.append(f"| {g} | " + " | ".join(map(str, row)) + " |")
    disagreements = [r for r in labelled if r.correctness != r.label]
    if disagreements:
        lines += ["", "Disagreements:", ""]
        lines += [f"- {r.id}: label {r.label}, judge {r.correctness}: {r.reason}" for r in disagreements]

    lines += ["", "## Metrics", "", "| Metric | Value |", "|---|---|",
              f"| Correctness, all answerable (abstention = 0) | {summary['correctness_all_answerable']:.3f} |",
              f"| Correctness, answered questions | {summary['correctness_answered']:.3f} |",
              f"| Grades of answered questions | {summary['grades_answered']} |",
              f"| Judge faithfulness (claims, in meaning) | {summary['faithfulness']:.3f} |",
              f"| Verifier claim support (figures) | {summary['verifier_claim_support']:.3f} |",
              f"| Judge tokens | {summary['judge_tokens']:,} |",
              f"| Errors | {summary['errors']} |", "",
              "## By category (answerable)", "", "| Category | n | Correctness | Faithfulness |", "|---|---|---|---|"]
    for cat in sorted({r.category for r in records if r.answerable}):
        rs = [r for r in records if r.answerable and r.category == cat and not r.error]
        lines.append(f"| {cat} | {len(rs)} | {_mean(r.correctness_score for r in rs):.3f} | "
                     f"{_mean(r.faithfulness for r in rs if r.faithfulness is not None):.3f} |")

    caught = [r for r in records if r.judged and r.correctness != "correct" and (r.verifier_supported or 0) == 1.0]
    lines += ["", f"## Passed the verifier, judged not correct ({len(caught)})", "",
              "| Id | Judge | Contradicted / missing | Unsupported claims |", "|---|---|---|---|"]
    for r in caught:
        facts = "; ".join(r.contradicted_facts or r.missing_facts)[:240].replace("|", "/")
        claims = "; ".join(r.unsupported_claims)[:200].replace("|", "/")
        lines.append(f"| {r.id} | {r.correctness} | {facts} | {claims or '-'} |")

    lines += ["", "## Per question", "", "| Id | Abstained | Judge | Faithfulness | Label | Reason |",
              "|---|---|---|---|---|---|"]
    for r in records:
        faith = "-" if r.faithfulness is None else f"{r.faithfulness:.2f}"
        reason = (r.error or r.reason)[:200].replace("|", "/")
        lines.append(f"| {r.id} | {r.abstained} | {r.correctness}{'' if r.judged else ' (rule)'} | {faith} | "
                     f"{r.label or '-'} | {reason} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--golden", type=Path, default=GOLDEN_PATH)
    parser.add_argument("--ids", nargs="+", help="only these question ids")
    parser.add_argument("--out", type=Path, help="default reports/judge_v0 (judge_v0_smoke with --ids)")
    parser.add_argument("--judge-providers", default="groq,gemini", help="never the model that wrote the answers")
    parser.add_argument("--judge-model", help="Groq model for the judge (default: settings.groq_model). Groq's free "
                        "limits are per model, so a second judge model has its own daily quota")
    parser.add_argument("--route", action="store_true",
                        help="answers from the routed agent (trend/comparison by Groq); judge those with a second "
                             "--judge-model too, since a model grading its own answers is biased")
    args = parser.parse_args()
    args.out = args.out or PROJECT_ROOT / "reports" / ("judge_v0_smoke" if args.ids else "judge_v0")
    logging.basicConfig(level=logging.WARNING)
    logging.getLogger("app.generation.llm").setLevel(logging.INFO)

    from app.generation.llm import build_llm
    from app.retrieval.factory import build_retriever

    settings = get_settings()
    routed_llm = build_llm(settings.model_copy(update={"llm_providers": "groq,ollama"})) if args.route else None
    agent = FinRAGAgent(build_retriever(settings), build_llm(settings), xbrl=XbrlStore.from_settings(),
                        token_budget=settings.context_token_budget, routed_llm=routed_llm)
    judge_settings = {"llm_providers": args.judge_providers} | ({"groq_model": args.judge_model} if args.judge_model else {})
    judge = Judge(build_llm(settings.model_copy(update=judge_settings)))
    labels = load_labels()
    previous = ({r["id"]: r["answer"] for r in json.loads(AGENT_REPORT.read_text())["records"]["agent"]}
                if AGENT_REPORT.exists() else {})
    questions = [q for q in load_golden(args.golden) if not args.ids or q.id in args.ids]

    records: list[JudgedRecord] = []
    for i, q in enumerate(questions, 1):
        start = time.perf_counter()
        r = agent.run(q.question, q.history).result
        rec = JudgedRecord(q.id, q.category, q.answerable, r.abstained, r.answer, "incorrect", 0.0,
                           label=labels.get(q.id), answer_model=r.model,
                           answer_matches_agent_v0=previous.get(q.id) == r.answer if q.id in previous else None,
                           verifier_supported=(sum(c.supported for c in r.claims) / len(r.claims)) if r.claims else None)
        if r.abstained:
            rec.correctness = "incorrect" if q.answerable else "correct"
            rec.correctness_score = 0.0 if q.answerable else 1.0
            rec.reason = "abstained (rule)"
        elif not q.answerable:
            rec.reason = "answered an unanswerable question (rule)"
        else:
            cited = [s for s in r.sources if s.id in r.cited_source_ids]
            try:
                res = judge.judge(q.retrieval_query, q.reference_answer, r.answer, cited)
            except LLMError as e:
                rec.error = str(e)[:300]
            else:
                j = res.judgment
                rec.judged = True
                rec.correctness, rec.correctness_score = j.correctness, res.correctness
                rec.faithfulness = res.faithfulness
                rec.missing_facts, rec.contradicted_facts = j.missing_facts, j.contradicted_facts
                rec.unsupported_claims = [f"{c.claim} ({c.verdict}: {c.reason})" for c in j.claims
                                          if c.verdict != "supported"]
                rec.reason, rec.provider, rec.judge_model = j.reason, res.response.provider, res.response.model
                rec.tokens = 0 if res.response.cached else res.response.usage.total
        records.append(rec)
        status = rec.error and "ERROR" or f"{rec.correctness}{'' if rec.judged else ' (rule)'}"
        print(f"[{i}/{len(questions)}] {q.id} {status}{f' (label {rec.label})' if rec.label else ''} "
              f"({time.perf_counter() - start:.1f} s)", flush=True)
        if rec.error and "daily limit" in rec.error:
            print("Judge providers hit their daily limits; stopping (rerun later: answers and judgments are cached).")
            break

    summary = summarize(records)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.with_suffix(".md").write_text(render_report(records, summary, args.out.stem), encoding="utf-8")
    args.out.with_suffix(".json").write_text(json.dumps({"summary": summary, "records": [asdict(r) for r in records]},
                                                        indent=1, ensure_ascii=False), encoding="utf-8")
    mismatched = [r.id for r in records if r.answer_matches_agent_v0 is False]
    print(json.dumps(summary, indent=1))
    if mismatched:
        print(f"Answers differ from agent_v0 for: {mismatched}")
    print(f"Wrote {args.out.with_suffix('.md')}")


if __name__ == "__main__":
    main()
