"""Can the judge catch a wrong answer on earnings releases? Grade deliberately wrong ones.

The earnings answers were all judged correct, which says nothing about whether the judge would notice an
error. These answers are wrong in the ways releases invite, each with a figure that really is in the
source: another period's column, an annual total, a non-GAAP figure, the next quarter's outlook. The
verifier passes all of them, so catching them is the judge's job.

Usage:
    python -m app.evaluation.run_judge_sensitivity
    python -m app.evaluation.run_judge_sensitivity --judge-model qwen/qwen3.8-27b --out reports/judge_sensitivity_qwen
"""

import argparse
import json
from pathlib import Path

from app.config import PROJECT_ROOT, get_settings
from app.evaluation.golden import load_golden, normalize
from app.evaluation.judge import Judge
from app.generation.context import Source
from app.generation.llm import LLMError, build_llm
from app.retrieval.store import ChunkStore

GOLDEN = PROJECT_ROOT / "data" / "eval" / "golden_earnings_v0.jsonl"
# (golden question, wrong answer, error type, text that must be in a cited chunk of the same company)
WRONG_ANSWERS = [
    ("E13", "NVIDIA's revenue for the three months ended October 27, 2024 was $30,040 million.", "prior-quarter column", "$30,040"),
    ("E07", "Tesla's free cash flow in Q3 2024 was $1,342 million.", "prior-quarter column", "1,342"),
    ("E05", "Google Cloud revenue in Q3 2024 was $8,411 million.", "year-ago column", "8,411"),
    ("E10", "Mastercard's net revenue in Q4 2024 was $28.2 billion.", "annual figure as the quarter's", "$28.2"),
    ("E04", "JPMorgan's reported net income in Q2 2023 was $13.3 billion.", "adjusted figure as reported", "$13.3 billion"),
    ("E16", "NVIDIA's revenue outlook for Q4 FY2025 was $43.0 billion.", "next quarter's outlook", "$43.0 billion"),
]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--judge-model", help="Groq model (default: settings.groq_model)")
    parser.add_argument("--out", type=Path, default=PROJECT_ROOT / "reports" / "judge_sensitivity")
    args = parser.parse_args()

    settings = get_settings()
    updates = {"llm_providers": "groq"} | ({"groq_model": args.judge_model} if args.judge_model else {})
    judge = Judge(build_llm(settings.model_copy(update=updates)))
    questions = {q.id: q for q in load_golden(GOLDEN)}
    chunks = [c for c in ChunkStore.from_processed(settings.processed_dir).chunks if c.fiscal_quarter]

    records = []
    for qid, answer, error_type, figure in WRONG_ANSWERS:
        q = questions[qid]
        ticker = q.evidence[0].ticker
        source = next(c for c in chunks if c.ticker == ticker and c.fiscal_year == q.evidence[0].fiscal_year
                      and figure.lower() in normalize(c.text).lower()) if qid != "E16" else next(
            c for c in chunks if c.ticker == ticker and figure.lower() in normalize(c.text).lower())
        record = {"id": qid, "error_type": error_type, "answer": answer, "source": source.chunk_id}
        try:
            result = judge.judge(q.retrieval_query, q.reference_answer, f"{answer} [S1]", [Source("S1", source, 1.0)])
            record |= {"correctness": result.judgment.correctness, "reason": result.judgment.reason,
                       "model": result.response.model}
        except LLMError as e:
            record |= {"correctness": None, "reason": str(e)[:200], "model": ""}
        records.append(record)
        print(f"{qid} {error_type}: {record['correctness']}", flush=True)

    graded = [r for r in records if r["correctness"]]
    summary = {"answers": len(records), "graded": len(graded), "errors": len(records) - len(graded),
               "caught": sum(r["correctness"] == "incorrect" for r in graded),
               "partial": sum(r["correctness"] == "partially_correct" for r in graded),
               "missed": sum(r["correctness"] == "correct" for r in graded)}
    summary["caught_rate"] = summary["caught"] / len(graded) if graded else float("nan")
    lines = [f"# Judge sensitivity: {args.out.stem}", "", "Generated by `python -m app.evaluation.run_judge_sensitivity`: "
             "deliberately wrong answers whose figures really are in the cited source. The verifier passes them.", "",
             f"Caught {summary['caught']} of {summary['graded']} graded ({summary['errors']} errors).", "",
             "| Id | Error type | Answer | Judge |", "|---|---|---|---|"]
    lines += [f"| {r['id']} | {r['error_type']} | {r['answer']} | {r['correctness'] or 'error'} |" for r in records]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.with_suffix(".md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    args.out.with_suffix(".json").write_text(json.dumps({"summary": summary, "records": records}, indent=1), encoding="utf-8")
    print(json.dumps(summary))


if __name__ == "__main__":
    main()
