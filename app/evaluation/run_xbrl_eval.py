"""XBRL tool evaluation: which golden-set figures can the company-facts tool supply?

For every answerable golden question, the rule-based analyzer (no LLM) gives tickers/years,
`detect_metrics` picks the company-level metrics, and the XBRL store looks the facts up. A
reference-answer figure is *covered* when one of those facts states it, using the verifier's
own number matching (scale- and rounding-aware: "$130.5 billion" = "$130,497 million", "126%" =
"+125.9%"). This shows where the tool can back up retrieval, and where it would be wrong to use it
(segment metrics, company-defined figures such as Amazon's net "cash capex").

Usage:
    python -m app.evaluation.run_xbrl_eval            # writes reports/xbrl_v0.{md,json}
"""

import argparse
import json
from collections import defaultdict
from dataclasses import asdict, dataclass
from pathlib import Path

from app.agent.analyze import QueryAnalyzer
from app.agent.xbrl import XbrlFact, XbrlStore, coverage, detect_metrics
from app.config import PROJECT_ROOT
from app.evaluation.build_golden import DEFAULT_PATH as GOLDEN_PATH
from app.evaluation.golden import GoldQuestion, load_golden
from app.generation.verify import _matches, extract_numbers
from app.ingestion.companies import COMPANIES


@dataclass
class XbrlRow:
    id: str
    category: str
    question: str
    metrics: tuple[str, ...]
    tickers: tuple[str, ...]
    years: tuple[int, ...]
    facts: list[str]  # citations
    gold_figures: list[str]
    covered: list[str]

    @property
    def coverage(self) -> float | None:
        return len(self.covered) / len(self.gold_figures) if self.gold_figures else None


def gold_figures(answer: str) -> list:
    return [n for n in extract_numbers(answer) if not (n.value < 10 and not n.percent and n.scale == 1)]


def covered_by(figures: list, facts: list[XbrlFact]) -> list[str]:
    fact_numbers = [n for f in facts for n in extract_numbers(f.text())]
    return [g.raw for g in figures if any(_matches(g, n) for n in fact_numbers)]


def evaluate(questions: list[GoldQuestion], store: XbrlStore) -> list[XbrlRow]:
    analyzer = QueryAnalyzer(None)
    rows = []
    for q in questions:
        if not q.answerable:
            continue
        a = analyzer.analyze(q.question, q.history)
        metrics = detect_metrics(a.standalone_query)
        tickers, years = a.filters.tickers or (), a.filters.fiscal_years or ()
        facts = store.lookup_many(tickers, metrics, years) if metrics and years else []
        figures = gold_figures(q.reference_answer)
        rows.append(XbrlRow(q.id, q.category, q.question, metrics, tuple(tickers), tuple(years),
                            [f.citation for f in facts], [g.raw for g in figures], covered_by(figures, facts)))
    return rows


def render(rows: list[XbrlRow], coverage_table: str) -> str:
    fired = [r for r in rows if r.facts]
    by_cat: dict[str, list[XbrlRow]] = defaultdict(list)
    for r in rows:
        by_cat[r.category].append(r)
    lines = [
        "# XBRL company-facts tool v0",
        "",
        "Generated by `python -m app.evaluation.run_xbrl_eval`. Filters from the rule-based analyzer",
        "(no LLM, no gold filters); metrics from `detect_metrics`; figures matched with the verifier's",
        "number matching.",
        "",
        "## Coverage of the corpus (10 companies x FY2022-2025)",
        "",
        "✓ = from the fiscal year's own 10-K, c = comparative in the next 10-K, - = not tagged.",
        "",
        coverage_table,
        "",
        "## Golden set: where the tool attaches facts",
        "",
        "| Category | Answerable q | Tool fires | Gold figures | Covered by XBRL |",
        "|---|---|---|---|---|",
    ]
    for cat, rs in sorted(by_cat.items()):
        figs = sum(len(r.gold_figures) for r in rs if r.facts)
        cov = sum(len(r.covered) for r in rs if r.facts)
        lines.append(f"| {cat} | {len(rs)} | {sum(bool(r.facts) for r in rs)} | {figs} | {cov} |")
    figs = sum(len(r.gold_figures) for r in fired)
    cov = sum(len(r.covered) for r in fired)
    lines += [f"| **all** | {len(rows)} | {len(fired)} | {figs} | {cov} ({cov / figs:.0%}) |" if figs else "",
              "", "## Per question (tool fired)", "",
              "| Id | Metrics | Facts | Gold figures | Covered |", "|---|---|---|---|---|"]
    for r in fired:
        lines.append(f"| {r.id} | {', '.join(r.metrics)} | {len(r.facts)} | {', '.join(r.gold_figures)} | "
                     f"{', '.join(r.covered) or '-'} |")
    missed = [r for r in rows if not r.facts and r.metrics]
    if missed:
        lines += ["", "Metric detected but no facts (no year in the question): "
                  + ", ".join(f"{r.id} ({', '.join(r.metrics)})" for r in missed)]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--golden", type=Path, default=GOLDEN_PATH)
    parser.add_argument("--out", type=Path, default=PROJECT_ROOT / "reports" / "xbrl_v0")
    args = parser.parse_args()

    store = XbrlStore.from_settings()
    rows = evaluate(load_golden(args.golden), store)
    report = render(rows, coverage(store, list(COMPANIES), [2022, 2023, 2024, 2025]))
    args.out.with_suffix(".md").write_text(report)
    args.out.with_suffix(".json").write_text(json.dumps([asdict(r) for r in rows], indent=2))
    print(report)


if __name__ == "__main__":
    main()
